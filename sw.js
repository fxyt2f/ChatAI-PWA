const SHELL_POINTER = new URL('./.__active_app_shell__', self.location.href).href;
const INSTALL_POINTER = new URL(`./.__install_shell_${SHELL_BUILD_ID}__`, self.location.href).href;
const RETIRED_PREFIX = new URL('./.__retired_shell__/', self.location.href).href;
const readers = new Map();
let shellRefresh = Promise.resolve();
const absolute = path => new URL(path, self.location.href).href;
const shellPaths = new Set(urlsToCache.map(path => new URL(path, self.location.href).pathname));
async function shellName() {
  const primary = await caches.open(CACHE_NAME);
  const pointer = await primary.match(SHELL_POINTER);
  return pointer ? pointer.text() : CACHE_NAME;
}
async function matchShell(name, request) {
  readers.set(name, (readers.get(name) || 0) + 1);
  try {
    const cache = await caches.open(name);
    return await cache.match(request);
  } finally {
    const count = readers.get(name) - 1;
    if (count) readers.set(name, count); else readers.delete(name);
  }
}
async function readShell(request) {
  // A pointer read may overlap cleanup, even before the reader can pin its cache.
  // Retry the latest committed pointer a bounded number of times before networking.
  let previous;
  for (let attempt = 0; attempt < 3; attempt++) {
    const name = await shellName();
    if (name === previous) break;
    previous = name;
    const cached = await matchShell(name, request);
    if (cached) return cached;
    if (request.mode === 'navigate') {
      const index = await matchShell(name, absolute('./index.html'));
      if (index) return index;
    }
  }
}
async function validateShell(cache) {
  for (const path of urlsToCache) {
    const response = await cache.match(absolute(path));
    if (!response?.ok) throw new Error('Incomplete app shell');
    const digest = await crypto.subtle.digest('SHA-256', await response.arrayBuffer());
    const hex = Array.from(new Uint8Array(digest), byte => byte.toString(16).padStart(2, '0')).join('');
    if (hex !== SHELL_INTEGRITY[path]) throw new Error('App shell release integrity mismatch');
  }
  for (const page of ['./', './index.html']) {
    const html = await (await cache.match(absolute(page))).text();
    const refs = new Set(Array.from(html.matchAll(/\b(?:src|href)\s*=\s*["']([^"']+)["']/g), m => absolute(m[1])));
    for (const asset of urlsToCache.filter(path => path.includes('?v=')))
      if (!refs.has(absolute(asset))) throw new Error('App shell reference mismatch');
    for (const ref of refs) {
      const url = new URL(ref);
      if (url.origin === self.location.origin && /\.(?:js|css)$/.test(url.pathname)
          && !urlsToCache.some(path => absolute(path) === ref)) throw new Error('Unlisted app shell reference');
    }
  }
}
async function buildShell() {
  const name = `${CACHE_NAME}-shell-${SHELL_BUILD_ID}-${crypto.randomUUID()}`;
  try {
    const cache = await caches.open(name);
    await cache.addAll(urlsToCache.map(path => new Request(absolute(path), { cache: 'no-store' })));
    await validateShell(cache);
    return name;
  } catch (error) { await caches.delete(name); throw error; }
}
async function cleanupShells() {
  const primary = await caches.open(CACHE_NAME);
  // Only retire previously published shells, never another worker's candidate.
  // Markers survive worker restarts; pins protect matches already in progress.
  for (const request of await primary.keys()) if (request.url.startsWith(RETIRED_PREFIX)) {
    const entry = await primary.match(request);
    if (!entry) continue;
    const name = await entry.text();
    if (name === await shellName() || readers.has(name)) continue;
    await caches.delete(name); await primary.delete(request);
  }
}
async function publishShell(name) {
  const primary = await caches.open(CACHE_NAME);
  const previous = await primary.match(SHELL_POINTER);
  const old = previous ? await previous.text() : null;
  await primary.put(SHELL_POINTER, new Response(name));
  // Failure of bookkeeping after committing the pointer must never delete the
  // new active cache or report a successful switch as a failed rebuild.
  try {
    if (old && old !== name) await primary.put(RETIRED_PREFIX + encodeURIComponent(old), new Response(old));
    await cleanupShells();
  } catch { /* A later successful update can retry retirement. */ }
}
self.addEventListener('install', event => {
  event.waitUntil((async () => {
    const name = await buildShell();
    try {
      const primary = await caches.open(CACHE_NAME);
      // The candidate is separate from the active pointer until activation.
      await primary.put(INSTALL_POINTER, new Response(name));
      // Existing clients decide when activation is safe; first installs activate normally.
    } catch (error) { await caches.delete(name); throw error; }
  })());
});
self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    const primary = await caches.open(CACHE_NAME);
    const candidate = await primary.match(INSTALL_POINTER);
    if (!candidate) throw new Error('Verified install candidate missing');
    const name = await candidate.text();
    // Revalidate after a possible worker restart; never claim a partial shell.
    await validateShell(await caches.open(name));
    await publishShell(name);
    await primary.delete(INSTALL_POINTER);
    await self.clients.claim();
    const names = await caches.keys();
    const version = name => name.match(/^chatai-pwa-cache-v(\d+)\.(\d+)\.(\d+)$/)?.slice(1).map(Number);
    const current = version(CACHE_NAME);
    await Promise.allSettled(names.filter(name => {
      const old = version(name);
      return old && old.some((value,i) => value < current[i] && old.slice(0,i).every((part,j) => part === current[j]));
    }).map(name => caches.delete(name)));
  })());
});
self.addEventListener('fetch', event => {
  const request = event.request, url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== self.location.origin) return;
  if (request.mode !== 'navigate' && !shellPaths.has(url.pathname)) return;
  event.respondWith((async () => {
    const cached = await readShell(request);
    if (cached) return cached;
    try { return await fetch(request); }
    catch { return new Response('Offline', { status: 503, headers: { 'Content-Type': 'text/plain; charset=utf-8' } }); }
  })());
});
self.addEventListener('message', event => {
  if (event.data?.action === 'skipWaiting') event.waitUntil(self.skipWaiting());
});
async function rebuildShell() {
  const name = await buildShell();
  try { await publishShell(name); }
  catch (error) { await caches.delete(name); throw error; }
}
self.addEventListener('message', event => {
  if (event.data?.action !== 'clearCache') return;
  const refresh = shellRefresh.catch(() => {}).then(rebuildShell);
  shellRefresh = refresh;
  event.waitUntil((async () => {
    let result;
    try { await refresh; result = { status: 'cacheCleared' }; }
    catch { result = { status: 'cacheClearFailed', error: 'アプリ資源の再取得に失敗しました。既存のキャッシュは保持しています。' }; }
    if (event.ports?.[0]) event.ports[0].postMessage(result);
    else if (event.source?.postMessage) event.source.postMessage(result);
    else for (const client of await self.clients.matchAll({ type: 'window', includeUncontrolled: true })) client.postMessage(result);
  })());
});
