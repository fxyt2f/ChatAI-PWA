async function cleanupShells() {
  const primary = await caches.open(CACHE_NAME);
  // Only retire previously published shells, never another worker's candidate.
  // Markers survive worker restarts; pins protect matches already in progress.
  for (const request of await primary.keys()) if (request.url.startsWith(RETIRED_PREFIX)) {
    const entry = await primary.match(request);
    if (!entry) continue;
    const name = await entry.text();
    if (name === await shellName() || readers.has(name)) continue;
    await caches.delete(name); await primary.delete(request);
  }
}
async function publishShell(name) {
  const primary = await caches.open(CACHE_NAME);
  const previous = await primary.match(SHELL_POINTER);
  const old = previous ? await previous.text() : null;
  await primary.put(SHELL_POINTER, new Response(name));
  // Failure of bookkeeping after committing the pointer must never delete the
  // new active cache or report a successful switch as a failed rebuild.
  try {
    if (old && old !== name) await primary.put(RETIRED_PREFIX + encodeURIComponent(old), new Response(old));
    await cleanupShells();
  } catch { /* A later successful update can retry retirement. */ }
}
