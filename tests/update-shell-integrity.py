"""Pin exact release bytes in the worker; run after editing an app-shell file.

The manifest is embedded in the worker so a stale CDN manifest cannot bless a
different release. --check validates working files and Git clean filters.
--check --staged reads the actual index blobs, including sw.js. GIT_INDEX_FILE
can select an isolated release index without changing the normal staging area.
"""
from pathlib import Path
import argparse
import hashlib
import json
import re
import subprocess
import sys

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
parser.add_argument('--staged', action='store_true', help='Check the actual Git index blobs')
args = parser.parse_args()
if args.staged and not args.check:
    parser.error('--staged requires --check')

root=Path(__file__).resolve().parents[1]
worker=root/'sw.js'


def git_output(*arguments):
    result = subprocess.run(['git', *arguments], cwd=root, capture_output=True)
    if result.returncode:
        sys.exit(result.stderr.decode('utf-8', errors='replace').strip())
    return result.stdout


def read_asset(name):
    if args.staged:
        return git_output('show', ':' + name)
    # A local-only hash can pass even though git add will publish other bytes.
    clean_oid = git_output('hash-object', '--path=' + name, '--', name)
    raw_oid = git_output('hash-object', '--no-filters', '--', name)
    if clean_oid != raw_oid:
        sys.exit(f'{name}: Git clean filters change the published bytes; normalize the working file first')
    return (root / name).read_bytes()


source=read_asset('sw.js').decode('utf-8')
paths=re.findall(r"'([^']+)'",source.split('const urlsToCache = [',1)[1].split('];',1)[0])
version=re.search(r"const CACHE_NAME = 'chatai-pwa-cache-v([^']+)'",source).group(1)
app=read_asset('app.js').decode('utf-8')
if f'const APP_VERSION = "{version}";' not in app or f'const APP_CACHE_VERSION = "v{version}";' not in app:
    sys.exit('Worker and app release versions differ')
if any('?v=' in name and name.split('?v=',1)[1]!=version for name in paths):
    sys.exit('Worker shell URLs contain mixed release versions')
assets = {}
digests = {}
for name in paths:
    filename = 'index.html' if name == './' else name[2:].split('?')[0]
    if filename not in assets:
        assets[filename] = read_asset(filename)
    digests[name] = hashlib.sha256(assets[filename]).hexdigest()
identity=hashlib.sha256(json.dumps(digests,sort_keys=True).encode()).hexdigest()[:20]
block=f"// SHELL_INTEGRITY_BEGIN (generated by tests/update-shell-integrity.py)\nconst SHELL_BUILD_ID = '{identity}';\nconst SHELL_INTEGRITY = {json.dumps(digests,indent=2)};\n// SHELL_INTEGRITY_END"
updated=re.sub(r'// SHELL_INTEGRITY_BEGIN.*?// SHELL_INTEGRITY_END',lambda _:block,source,flags=re.S)
if args.check:
    if updated!=source:sys.exit('App shell integrity manifest is stale; run python -B tests/update-shell-integrity.py')
    location = 'staged Git blobs' if args.staged else 'working files and Git clean filters'
    print(f'App shell integrity manifest matches all {len(digests)} release assets ({location})')
else:
    worker.write_text(updated,encoding='utf-8',newline='\n')
    print('Pinned',len(digests),'shell assets; build',identity)
