"""Pin exact release bytes in the worker; run after editing an app-shell file.

The manifest is embedded in the worker so a stale CDN manifest cannot bless a
different release. --check is read-only and suitable for validation.
"""
from pathlib import Path
import hashlib, json, re, sys
root=Path(__file__).resolve().parents[1]
worker=root/'sw.js'
source=worker.read_text(encoding='utf-8')
paths=re.findall(r"'([^']+)'",source.split('const urlsToCache = [',1)[1].split('];',1)[0])
version=re.search(r"const CACHE_NAME = 'chatai-pwa-cache-v([^']+)'",source).group(1)
app=(root/'app.js').read_text(encoding='utf-8')
if f'const APP_VERSION = "{version}";' not in app or f'const APP_CACHE_VERSION = "v{version}";' not in app:
    sys.exit('Worker and app release versions differ')
if any('?v=' in name and name.split('?v=',1)[1]!=version for name in paths):
    sys.exit('Worker shell URLs contain mixed release versions')
digests={name:hashlib.sha256((root/('index.html' if name=='./' else name[2:].split('?')[0])).read_bytes()).hexdigest() for name in paths}
identity=hashlib.sha256(json.dumps(digests,sort_keys=True).encode()).hexdigest()[:20]
block=f"// SHELL_INTEGRITY_BEGIN (generated by tests/update-shell-integrity.py)\nconst SHELL_BUILD_ID = '{identity}';\nconst SHELL_INTEGRITY = {json.dumps(digests,indent=2)};\n// SHELL_INTEGRITY_END"
updated=re.sub(r'// SHELL_INTEGRITY_BEGIN.*?// SHELL_INTEGRITY_END',lambda _:block,source,flags=re.S)
if '--check' in sys.argv:
    if updated!=source:sys.exit('App shell integrity manifest is stale; run python -B tests/update-shell-integrity.py')
    print('App shell integrity manifest matches all release assets')
else:
    worker.write_text(updated,encoding='utf-8',newline='\n')
    print('Pinned',len(digests),'shell assets; build',identity)
